"""Select the pinned CC0 Kenney keyboard/mouse prompts from the official ZIP.

The resulting PNGs are checked-in source assets. This is an explicit intake
tool, not a build-time downloader, and never extracts arbitrary ZIP paths.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import zipfile


ROOT = Path(__file__).resolve().parents[1]
SOURCE_URL = "https://kenney.nl/assets/input-prompts"
DOWNLOAD_URL = ("https://kenney.nl/media/pages/assets/input-prompts/"
                "8de120163f-1783763952/kenney_input-prompts_1.5.zip")
ARCHIVE_SHA256 = "ac2fcf599080b0f3ba2d174c9474db6df1a0e96ff0662580e2da79a122ab78a1"
KEYS = (
    "space", "enter", "escape", "w", "a", "s", "d", "arrow_up",
    "arrow_down", "arrow_left", "arrow_right", "q", "e", "x", "y",
    "p", "tab", "shift", "ctrl", "r", "f", "backspace",
)
MOUSE = ("left", "right", "scroll", "scroll_up", "scroll_down")
PROMPTS = tuple(f"keyboard_{key}.png" for key in KEYS) + tuple(
    f"mouse_{button}.png" for button in MOUSE
)
COMPOSITES = {"keyboard_buttons_atlas.png": (512, 256),
              "keyboard_controls_diagram.png": (1024, 256)}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prepare(archive: Path, output: Path) -> dict:
    archive_data = archive.read_bytes()
    if sha256(archive_data) != ARCHIVE_SHA256:
        raise ValueError("Kenney archive differs from the pinned official Input Prompts 1.5A")
    with zipfile.ZipFile(archive) as source:
        license_data = source.read("License.txt")
        if b"Creative Commons Zero, CC0" not in license_data:
            raise ValueError("Kenney archive is missing its original CC0 license")
        files = {name: source.read(f"Keyboard & Mouse/Default/{name}") for name in PROMPTS}
    output.mkdir(parents=True, exist_ok=True)
    (output / "LICENSE.txt").write_bytes(license_data)
    entries = []
    for name, data in files.items():
        # PNG IHDR carries the authored 64x64 frame; the source bytes stay intact.
        if (data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR" or
                int.from_bytes(data[16:20], "big") != 64 or
                int.from_bytes(data[20:24], "big") != 64):
            raise ValueError(f"Prompt frame differs from its 64x64 PNG contract: {name}")
        (output / name).write_bytes(data)
        entries.append({"file": name, "archive_entry": f"Keyboard & Mouse/Default/{name}",
                        "sha256": sha256(data), "width": 64, "height": 64})
    manifest = {
        "name": "Kenney Input Prompts", "version": "1.5A",
        "author": "Kenney", "source_url": SOURCE_URL, "download_url": DOWNLOAD_URL,
        "archive_sha256": ARCHIVE_SHA256, "license": "CC0-1.0",
        "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
        "license_sha256": sha256(license_data),
        "variant": "Keyboard & Mouse/Default filled", "files": entries,
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    return manifest


def write_header(assets: Path, output: Path) -> None:
    """Embed the exact checked PNG files, with no image-decoder dependency."""
    manifest = json.loads((assets / "manifest.json").read_text(encoding="utf-8"))
    if (manifest.get("archive_sha256") != ARCHIVE_SHA256 or
            manifest.get("version") != "1.5A" or manifest.get("license") != "CC0-1.0"):
        raise ValueError("Prompt manifest differs from the supported official Kenney pack")
    records = manifest.get("files", [])
    expected = PROMPTS + tuple(COMPOSITES)
    if tuple(record.get("file") for record in records) != expected:
        raise ValueError("Prompt manifest differs from the supported keyboard/mouse subset")
    if sha256((assets / "LICENSE.txt").read_bytes()) != manifest.get("license_sha256"):
        raise ValueError("Prompt license differs from the checked manifest")
    lines = [
        "// Generated by tools/prepare_input_prompts.py; do not edit.",
        "// Kenney Input Prompts 1.5A, CC0-1.0. https://kenney.nl/assets/input-prompts",
        "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
        "namespace Doritos::Graphics::InputPrompts {",
        "struct Descriptor {",
        "    const char* name;",
        "    const uint8_t* bytes;",
        "    size_t size;",
        "    uint32_t width;",
        "    uint32_t height;",
        "};", "",
    ]
    descriptors = []
    for record in records:
        name = record["file"]
        data = (assets / name).read_bytes()
        if sha256(data) != record.get("sha256"):
            raise ValueError(f"Prompt source differs from its manifest hash: {name}")
        width, height = COMPOSITES.get(name, (64, 64))
        if (record.get("width") != width or record.get("height") != height or
                data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR" or
                int.from_bytes(data[16:20], "big") != width or
                int.from_bytes(data[20:24], "big") != height):
            raise ValueError(f"Prompt dimensions differ from the supported PNG frame: {name}")
        symbol = name.removesuffix(".png").removesuffix("_outline")
        lines.append(f"inline constexpr uint8_t {symbol}[] = {{")
        for begin in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[begin:begin + 16]) + ",")
        lines.extend(["};", ""])
        descriptors.append(f'    {{"{symbol}", {symbol}, sizeof({symbol}), {width}, {height}}},')
    lines.extend(["inline constexpr Descriptor descriptors[] = {", *descriptors,
                  "};", "", "} // namespace Doritos::Graphics::InputPrompts", ""])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


def compose(assets: Path, font_path: Path) -> None:
    """Make owned atlas/control-guide layouts from checked CC0 source icons."""
    from PIL import Image, ImageDraw, ImageFont

    manifest = json.loads((assets / "manifest.json").read_text(encoding="utf-8"))
    source_records = manifest["files"][:len(PROMPTS)]
    if tuple(record["file"] for record in source_records) != PROMPTS:
        raise ValueError("Cannot compose a different prompt source subset")
    for record in source_records:
        if sha256((assets / record["file"]).read_bytes()) != record["sha256"]:
            raise ValueError(f"Composite source differs from its checked hash: {record['file']}")
    icons = {name.removesuffix(".png"): Image.open(assets / name).convert("RGBA")
             for name in PROMPTS}
    atlas = Image.new("RGBA", (512, 256))
    for slot, name in enumerate(("keyboard_space", "keyboard_escape", "keyboard_x", "keyboard_r")):
        atlas.alpha_composite(icons[name], (slot * 64, 0))
    atlas.save(assets / "keyboard_buttons_atlas.png")
    guide = Image.new("RGBA", (1024, 256))
    draw = ImageDraw.Draw(guide)
    font = ImageFont.truetype(str(font_path), 21)

    def tile(index: int, title: str, names: tuple[str, ...]) -> None:
        x, y = (index % 4) * 256, (index // 4) * 128
        box = draw.textbbox((0, 0), title, font=font)
        draw.text((x + (256 - box[2]) // 2, y + 3), title, fill="white", font=font)
        size = 60 if len(names) > 2 else 84
        start = x + (256 - size * len(names)) // 2
        for ordinal, name in enumerate(names):
            guide.alpha_composite(icons[name].resize((size, size), Image.Resampling.LANCZOS),
                                  (start + ordinal * size, y + 34))

    tile(0, "Move / crouch / slide", ("keyboard_w", "keyboard_a", "keyboard_s", "keyboard_d"))
    tile(1, "Jump", ("keyboard_space",))
    tile(2, "Pause", ("keyboard_escape", "keyboard_p"))
    tile(3, "Restart area", ("keyboard_r",))
    tile(4, "Restart level", ("keyboard_backspace",))
    tile(5, "Boost", ("keyboard_q", "keyboard_e", "keyboard_shift", "keyboard_ctrl"))
    tile(6, "Menu: select", ("keyboard_enter", "mouse_left"))
    tile(7, "Menu: back", ("keyboard_escape", "mouse_right"))
    guide.save(assets / "keyboard_controls_diagram.png")
    manifest["files"] = source_records + [
        {"file": name, "sha256": sha256((assets / name).read_bytes()),
         "width": size[0], "height": size[1], "origin": "owned composition of CC0 Kenney icons",
         "recipe": "tools/prepare_input_prompts.py compose-v1"}
        for name, size in COMPOSITES.items()
    ]
    manifest["composition"] = {"recipe": "compose-v1", "font": font_path.name,
                               "font_sha256": sha256(font_path.read_bytes())}
    (assets / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, nargs="?", help="Downloaded official ZIP; source hash is verified")
    parser.add_argument("--output", type=Path, default=ROOT / "assets" / "input-prompts")
    parser.add_argument("--header", type=Path, help="Emit a C++ header from the checked PNG source assets")
    parser.add_argument("--compose", action="store_true", help="Create owned layouts; requires Pillow")
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/arial.ttf"))
    args = parser.parse_args()
    if args.archive is None and args.header is None and not args.compose:
        parser.error("provide the official archive or --header output")
    if args.archive is not None:
        result = prepare(args.archive, args.output)
        print(f"Prepared {len(result['files'])} unmodified CC0 prompt PNGs in {args.output}")
    if args.compose:
        compose(args.output, args.font)
        print(f"Composed two owned keyboard/mouse layouts in {args.output}")
    if args.header is not None:
        write_header(args.output, args.header)
        print(f"Embedded {len(PROMPTS) + len(COMPOSITES)} checked CC0 prompt PNGs in {args.header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
